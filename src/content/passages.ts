/** 空欄の採点。数値は有効数字 2 桁ぶんの誤差を認める */
export function checkBlank(b: Blank, input: string): boolean {
  if (b.type === 'choice') return input === b.answer;
  if (b.type === 'formula') return normalizeFormula(input) === b.answer;
  const x = parseFloat(input), a = b.answer as number;
  return !Number.isNaN(x) && Math.abs(x - a) <= Math.max(Math.abs(a) * 0.02, 1e-9);
}
