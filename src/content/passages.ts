/** 京大形式のリード文課題。長い文章を読み、空欄を埋める。すべて自作の文章 */
export interface Blank {
  id: string;
  type: 'formula' | 'number' | 'choice';
  answer: string | number;
  choices?: string[];
  unit?: string;
  why: string;
}
export interface Passage {
  id: string;
  title: string;
  field: string;
  /** 本文。空欄は [ア] のように書く */
  text: string;
  blanks: Blank[];
}

