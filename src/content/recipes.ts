export type MachineKind = 'separator' | 'electrolyzer' | 'reactor' | 'battery' | 'collector';

export interface Recipe {
  id: string;
  machine: MachineKind;
  name: string;
  /** [物質id, 係数] */
  inputs: [string, number][];
  /** 電池では先頭が電子 */
  outputs: [string, number][];
  /** 電解槽：生成物ごとに、生じる極。c 陰極、a 陽極、x 溶液全体（どちらに書いてもよい）。省くと 'ca'、3 つ目以降は x */
  poles?: string;
  /** 生成物の比が決まらない反応。原子の数が合う係数ならどれでも正解にする */
  free?: boolean;
  /** 装置ごとの条件欄で正解になる選択肢 */
  accept: string[];
  /** 1回の反応にかかる秒数 */
  time: number;
  /** 混合物や高分子がからむので係数を問わない */
  loose?: boolean;
  /** 混ぜる比だけを問う（緩衝液など）。原料の係数だけ採点する */
  mix?: boolean;
  /** 可逆反応：平衡を生成物側へ動かす温度と圧力 */
  shift?: string;
  /** 運転条件の計算。設定が合ったあとに問う */
  ask?: { text: string; answer: number; unit: string; how: string };
  /** 電池：負極・正極の活物質 */
  neg?: string;
  pos?: string;
  /** 答えを見たときに出す解説 */
  note: string;
  /** 教科書での単元 */
  source: string;
}

